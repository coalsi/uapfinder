"""``skynet-edge autoconfig``: detected hardware + credentials + calibration -> ``/etc/skynet/edge.yaml``.

Inputs, all optional:

* the detection result (``detect.Detector``), also saved to ``/run/skynet/detect.json``;
* ``/var/lib/skynet/credentials.json`` (enrollment);
* ``/var/lib/skynet/calibration.json`` (star calibration, format in ``calibration.py``);
* ``/etc/skynet/defaults.yaml`` (image defaults, e.g. ``enroll_url`` and the ADS-B feed);
* ``/etc/skynet/edge.local.yaml``: hand edits, deep-merged over the result.

With nothing attached and nothing enrolled the result is still a valid
configuration (the node then waits, see ``waiting.py``). If the local
overrides make the configuration invalid, the generated configuration is
written without them and the error is reported (``/run/skynet/autoconfig.json``
and the status page), so a typo cannot take the node off the air.

ADS-B: a local receiver (RTL-SDR, decoded by ``readsb`` into
``/run/readsb/aircraft.json``) is preferred. Without one, an online
ADSBx-v2-compatible community feed is polled (default adsb.lol,
``https://api.adsb.lol/v2/point/{lat}/{lon}/{dist}``) every 5 s for a 40 nm
radius around the node; the node's position, rounded to 0.01 deg (about
1 km), is therefore sent to that service. ``adsb_online: false`` in
``defaults.yaml`` or ``edge.local.yaml`` turns that off.
"""

from __future__ import annotations

import copy
import logging
import os
import shutil
from pathlib import Path
from typing import Any, Dict, Optional, Tuple

import yaml

from ..config import ConfigError, parse_config
from .calibration import calibration_age_days, load_calibration
from .credentials import load_credentials
from .paths import Paths
from .util import atomic_write, read_text, run, write_json

log = logging.getLogger(__name__)

HEADER = ("# Generated by `skynet-edge autoconfig` at every start of skynet-edge.service.\n"
          "# Do not edit: put changes in edge.local.yaml (same structure; it overrides this file).\n")
MARKER = "Generated by `skynet-edge autoconfig`"

DEFAULTS: Dict[str, Any] = {
    "enroll_url": None,
    "adsb_online": True,
    # adsb.lol: ODbL data, ADSBx-v2-compatible, dynamic rate limits. Alternative:
    # https://api.airplanes.live/v2/point/{lat}/{lon}/{dist} (1 request/s, non-commercial).
    "adsb_online_url": "https://api.adsb.lol/v2/point/{lat}/{lon}/{dist}",
    "adsb_online_poll_s": 5.0,
    "adsb_radius_nm": 40.0,
    "readsb_aircraft_json": "/run/readsb/aircraft.json",
    # Recommended kit: IMX477 (Raspberry Pi HQ camera module) with a ~90 deg M12 lens.
    "lens_fov_h_deg": 90.0,
    "uvc_fov_h_deg": 78.0,
    "pps_device": None,
}

# Angular uncertainty reported until the stars give a real solution.
SIGMA_PRIOR_DEG = 45.0  # "pointing up, heading unknown"
SIGMA_IMU_DEG = 10.0  # BNO055: unknown magnetic declination and mount offsets
SIGMA_STARCAL_FLOOR_DEG = 0.02


def deep_merge(base: Dict[str, Any], over: Dict[str, Any]) -> Dict[str, Any]:
    out = copy.deepcopy(base)
    for k, v in over.items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = deep_merge(out[k], v)
        else:
            out[k] = copy.deepcopy(v)
    return out


def load_yaml(path: Path) -> Tuple[Dict[str, Any], Optional[str]]:
    """(mapping, error). A missing file is an empty mapping without error."""
    text = read_text(path, 1 << 20)
    if text is None:
        return {}, None
    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError as exc:
        return {}, f"{path}: invalid YAML: {exc}"
    if data is None:
        return {}, None
    if not isinstance(data, dict):
        return {}, f"{path}: must be a mapping"
    return data, None


def load_defaults(paths: Paths) -> Dict[str, Any]:
    data, err = load_yaml(paths.defaults_yaml)
    if err:
        log.warning("%s", err)
    out = dict(DEFAULTS)
    out.update({k: v for k, v in data.items() if k in DEFAULTS})
    setup = paths.setup_dir / "settings.json"
    from .util import read_json

    over = read_json(setup)
    if isinstance(over, dict) and isinstance(over.get("enroll_url"), str):
        out["enroll_url"] = over["enroll_url"]
    return out


def clip_retention_gb(state_dir: Path) -> float:
    """Clip budget: 40 % of the file system holding the clips, between 2 and 50 GB."""
    try:
        total = shutil.disk_usage(state_dir).total / 1e9
    except OSError:
        return 10.0
    return round(max(2.0, min(50.0, 0.4 * total)), 1)


def generate(det: Dict[str, Any], creds: Any, calib: Optional[Dict[str, Any]], defaults: Dict[str, Any],
             paths: Paths, adsb_online: Optional[bool] = None) -> Dict[str, Any]:
    """The configuration mapping for this node (before local overrides)."""
    cfg: Dict[str, Any] = {}
    # --- identity and server ------------------------------------------------------
    if creds is not None:
        d = creds.data
        cfg["node"] = {"node_id": creds.node_id, "credentials_file": str(paths.credentials)}
        server: Dict[str, Any] = {"transport": d["transport"], "udp_port": d.get("udp_port", 9999)}
        if d.get("udp_host"):
            server["udp_host"] = d["udp_host"]
        if d.get("https_base_url"):
            server["https_base_url"] = d["https_base_url"]
        cfg["server"] = server
    else:
        cfg["node"] = {"node_id": "unenrolled", "credentials_file": str(paths.credentials)}
        cfg["server"] = {"transport": "none"}

    # --- camera ---------------------------------------------------------------------
    cam = det.get("camera") or {"kind": "none"}
    if cam.get("kind") == "uvc":
        camera: Dict[str, Any] = {"source": "v4l2", "device": cam["device"], "width": 1280, "height": 720,
                                  "fps": 30.0, "fov_h_deg": float(defaults["uvc_fov_h_deg"])}
    else:
        camera = {"source": "gstreamer", "sensor_id": int(cam.get("sensor_id", 0) or 0), "width": 1920,
                  "height": 1080, "fps": 60.0, "fov_h_deg": float(defaults["lens_fov_h_deg"])}
    attitude: Dict[str, Any]
    imu = det.get("imu") or {}
    cal_ok = calib is not None and calib.get("ok", True)
    if cal_ok and calib is not None:
        if (calib.get("width"), calib.get("height")) == (camera["width"], camera["height"]) and calib.get("fx"):
            camera["intrinsics"] = {"fx": float(calib["fx"]), "fy": float(calib.get("fy") or calib["fx"]),
                                    "cx": float(calib["cx"]), "cy": float(calib["cy"]),
                                    "dist": [float(calib.get("k1") or 0.0), float(calib.get("k2") or 0.0), 0.0, 0.0]}
        else:
            log.warning("calibration is for %sx%s, camera runs %dx%d: using the pointing but not the lens model",
                        calib.get("width"), calib.get("height"), camera["width"], camera["height"])
        attitude = {"source": "static", "yaw_deg": round(float(calib["yaw_deg"]) % 360.0, 4),
                    "pitch_deg": round(float(calib["pitch_deg"]), 4), "roll_deg": round(float(calib["roll_deg"]), 4),
                    "pointing_source": "starcal",
                    "pointing_sigma_deg": round(max(SIGMA_STARCAL_FLOOR_DEG, float(calib.get("rms_deg") or 0.1)), 4)}
    elif imu.get("kind") == "bno055":
        attitude = {"source": "bno055", "yaw_deg": 0.0, "pitch_deg": 90.0, "roll_deg": 0.0,
                    "bno055": {"i2c_bus": int(imu["bus"]), "address": int(imu["address"])},
                    "pointing_source": "imu", "pointing_sigma_deg": SIGMA_IMU_DEG}
    else:
        attitude = {"source": "static", "yaw_deg": 0.0, "pitch_deg": 90.0, "roll_deg": 0.0,
                    "pointing_source": "prior", "pointing_sigma_deg": SIGMA_PRIOR_DEG}
    cfg["camera"] = camera
    cfg["attitude"] = attitude

    # --- GPS ------------------------------------------------------------------------------
    gps = det.get("gps") or {}
    if gps.get("kind") == "serial" and not gps.get("gpsd"):
        cfg["gps"] = {"source": "nmea", "nmea_device": gps["device"], "nmea_baud": int(gps.get("baud", 9600))}
    else:
        cfg["gps"] = {"source": "gpsd"}

    # --- ADS-B ------------------------------------------------------------------------------
    online = defaults.get("adsb_online", True) if adsb_online is None else adsb_online
    if (det.get("adsb") or {}).get("rtlsdr"):
        cfg["adsb"] = {"source": "dump1090", "file_path": defaults["readsb_aircraft_json"],
                       "poll_interval_s": 1.0}
    elif online and defaults.get("adsb_online_url"):
        cfg["adsb"] = {"source": "adsbx_v2", "url": defaults["adsb_online_url"],
                       "poll_interval_s": float(defaults["adsb_online_poll_s"]),
                       "radius_nm": float(defaults["adsb_radius_nm"]), "query_decimals": 2, "timeout_s": 5.0}
    else:
        cfg["adsb"] = {"source": "none"}

    # --- storage, health, appliance hooks ---------------------------------------------------
    cfg["clips"] = {"storage_dir": str(paths.clips), "retention_max_gb": clip_retention_gb(paths.state)}
    cfg["appliance"] = {"run_dir": str(paths.run),
                        "restart_on_change": [str(paths.credentials), str(paths.calibration)]}
    return cfg


def apply_local(generated: Dict[str, Any], local: Dict[str, Any]) -> Dict[str, Any]:
    merged = deep_merge(generated, local)
    node_local = local.get("node") or {}
    if isinstance(node_local, dict) and (node_local.get("key_hex") or node_local.get("key_file")):
        merged["node"].pop("credentials_file", None)  # hand-configured key wins
    return merged


def summary(det: Dict[str, Any], cfg: Dict[str, Any], calib: Optional[Dict[str, Any]]) -> Dict[str, Any]:
    age = calibration_age_days(calib)
    return {"camera": cfg["camera"]["source"], "gps": cfg["gps"]["source"], "adsb": cfg["adsb"]["source"],
            "attitude": cfg["attitude"].get("pointing_source"), "calibration_age_days": age,
            "enrolled": cfg["node"].get("node_id") != "unenrolled"}


def autoconfig(paths: Optional[Paths] = None, det: Optional[Dict[str, Any]] = None, write: bool = True,
               detector_kwargs: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    """Run the whole step; returns ``{"ok", "config", "error", "summary", "detect"}``."""
    from .detect import Detector

    paths = paths or Paths.from_env()
    if det is None:
        det = Detector(**(detector_kwargs or {})).detect()
    creds = load_credentials(paths.credentials)
    calib = load_calibration(paths.calibration)
    defaults = load_defaults(paths)
    local, local_err = load_yaml(paths.local_yaml)
    adsb_online = local.pop("adsb_online", None) if isinstance(local.get("adsb_online"), bool) else None
    gen = generate(det, creds, calib, defaults, paths, adsb_online)
    error = local_err
    final = apply_local(gen, local)
    try:
        parse_config(final)
    except ConfigError as exc:
        error = f"edge.local.yaml ignored: {exc}"
        final = gen
        parse_config(final)  # the generated config itself must always be valid
    if error:
        log.error("%s", error)
    result = {"ok": error is None, "error": error, "config": final, "summary": summary(det, gen, calib),
              "detect": det}
    if write:
        text = HEADER + yaml.safe_dump(final, sort_keys=False, default_flow_style=False)
        atomic_write(paths.edge_yaml, text, 0o644)
        try:
            paths.run.mkdir(parents=True, exist_ok=True)
            write_json(paths.detect_json, det)
            write_json(paths.run / "autoconfig.json", {k: result[k] for k in ("ok", "error", "summary")})
            if os.geteuid() == 0:  # the setup page (user skynet) reads these
                _chown_like(paths.run, paths.detect_json, paths.run / "autoconfig.json")
        except OSError as exc:
            log.warning("cannot write %s: %s", paths.run, exc)
    return result


def _chown_like(ref: Path, *files: Path) -> None:
    try:
        st = ref.stat()
        for f in files:
            os.chown(f, st.st_uid, st.st_gid)
    except OSError:
        pass


# --- chrony (root only, from the skynet-edge.service ExecStartPre) -------------------------


def chrony_template_dir() -> Optional[Path]:
    for cand in (Path("/opt/skynet/src/edge/deploy/jetson"), Path(__file__).resolve().parents[2] / "deploy/jetson"):
        if (cand / "chrony-gps-pps.conf").exists():
            return cand
    return None


def chrony_conf(det: Dict[str, Any], defaults: Dict[str, Any], template_dir: Path) -> str:
    pps = defaults.get("pps_device") or (det.get("pps") or {}).get("device")
    if pps:
        text = (template_dir / "chrony-gps-pps.conf").read_text(encoding="utf-8")
        return text.replace("@PPS_DEVICE@", str(pps))
    return (template_dir / "chrony-gps-nopps.conf").read_text(encoding="utf-8")


def update_chrony(det: Dict[str, Any], paths: Paths, conf_path: Path = Path("/etc/chrony/conf.d/skynet-gps.conf"),
                  runner: Any = run) -> bool:
    """Write the chrony refclock config for the detected PPS; restart chrony if it changed."""
    tdir = chrony_template_dir()
    if tdir is None:
        log.warning("chrony templates not found; leaving %s alone", conf_path)
        return False
    want = chrony_conf(det, load_defaults(paths), tdir)
    if read_text(conf_path) == want:
        return False
    atomic_write(conf_path, want, 0o644)
    log.info("chrony: %s updated (PPS %s)", conf_path, (det.get("pps") or {}).get("device") or "none")
    runner(["systemctl", "--no-block", "try-restart", "chrony.service"], timeout=10.0)
    return True

/**
 * Build-time site configuration from PUBLIC_* environment variables
 * (see .env.example and README.md). Vite inlines these at build time, so a
 * change needs a rebuild.
 */
import { joinBase, trimTrailingSlashes, withQuery } from "./lib/urls";

const env = import.meta.env;

function clean(value: string | undefined): string | undefined {
  const v = value?.trim();
  return v ? v : undefined;
}

export const SITE_NAME = "UAP Finder";

/** A root-relative path on this site ("/host/") under the deployment's base path
 * (Astro's `base`, from PUBLIC_BASE_PATH). Use it for every internal link. */
export function sitePath(path: string): string {
  return joinBase(env.BASE_URL ?? "/", path);
}

/** Source repository, without a trailing slash. */
export const REPO_URL = trimTrailingSlashes(clean(env.PUBLIC_REPO_URL) ?? "https://github.com/coalsi/uapfinder");

/** Git ref the documentation and download links point at; HEAD is the default branch. */
export const REPO_REF = clean(env.PUBLIC_REPO_REF) ?? "HEAD";

/** Contact address, or null to hide every contact-email element. */
export const CONTACT_EMAIL: string | null = clean(env.PUBLIC_CONTACT_EMAIL) ?? null;

/** API origin; "" means same origin as the site. */
export const API_BASE = trimTrailingSlashes(clean(env.PUBLIC_API_BASE) ?? "");

/** Live 3D map (another app, deployed at <base>/map/ by default). */
export const MAP_URL = clean(env.PUBLIC_MAP_URL) ?? sitePath("/map/");

export const COVERAGE_MAP_URL = withQuery(MAP_URL, { layer: "coverage" });

const tree = (path: string) => `${REPO_URL}/tree/${REPO_REF}/${path}`;
const blob = (path: string) => `${REPO_URL}/blob/${REPO_REF}/${path}`;

export const links = {
  repo: REPO_URL,
  edgeReadme: tree("edge"),
  serverCode: tree("server"),
  dashboardCode: tree("dashboard"),
  siteCode: tree("site"),
  mathDoc: blob("docs/MATH.md"),
  protocolDoc: blob("docs/PROTOCOL.md"),
  apiDoc: blob("docs/API.md"),
  edgeGuide: blob("edge/README.md"),
  jetsonImageGuide: blob("edge/deploy/image/README.md"),
  macStudioGuide: blob("deploy/mac-studio/README.md"),
  serverGuide: blob("server/README.md"),
  exampleConfig: blob("edge/config/example.yaml"),
  priceSources: blob("site/SOURCES.md"),
  issues: `${REPO_URL}/issues`,
  map: MAP_URL,
  coverageMap: COVERAGE_MAP_URL,
} as const;

/** Source archives of REPO_REF, generated by GitHub on request. */
export const downloads = {
  zip: `${REPO_URL}/archive/${REPO_REF}.zip`,
  tarball: `${REPO_URL}/archive/${REPO_REF}.tar.gz`,
  clone: `git clone ${REPO_URL}.git`,
} as const;

/** "Prices as of" month for the hardware list (update with the prices). */
export const PRICES_AS_OF = "October 2026";

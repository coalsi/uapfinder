import { expect, test } from "@playwright/test";
import { join } from "node:path";
import { PAGES } from "../../src/lib/pages";
import { collectErrors, mockNetwork, SCREENSHOT_DIR } from "./helpers";

const ALL = [...PAGES.map((p) => ({ path: p.path, name: p.name, status: 200 })), { path: "/no-such-page/", name: "404", status: 404 }];

test.describe("pages @screenshots", () => {
  for (const p of ALL) {
    test(`${p.name}: SEO basics, layout and screenshot`, async ({ page }, info) => {
      const errors = collectErrors(page, { allowDocumentStatus: p.status === 404 });
      // Home is shown with live figures; the degraded state has its own test and screenshot.
      await mockNetwork(page, p.name === "home" ? { stats: "ok", volunteers: "ok" } : {});
      const res = await page.goto(p.path, { waitUntil: "load" });
      expect(res?.status()).toBe(p.status);

      await expect(page).toHaveTitle(/UAP Finder/);
      await expect(page.locator("h1")).toHaveCount(1);
      const description = await page.locator('meta[name="description"]').getAttribute("content");
      expect(description?.length ?? 0).toBeGreaterThan(50);
      expect(await page.locator('meta[property="og:image"]').getAttribute("content")).toMatch(/^https?:\/\/.+\/og\.png$/);
      if (p.status === 200) {
        expect(await page.locator('link[rel="canonical"]').getAttribute("href")).toMatch(new RegExp(`${p.path}$`));
      } else {
        await expect(page.locator('meta[name="robots"]')).toHaveAttribute("content", "noindex");
      }

      // Every informative SVG has an accessible name; decorative ones are hidden.
      const unnamed = await page.$$eval("svg", (svgs) =>
        svgs.filter((s) => s.getAttribute("aria-hidden") !== "true" && !s.closest("[aria-hidden=true]") && !(s.getAttribute("role") === "img" && (s.getAttribute("aria-labelledby") || s.getAttribute("aria-label")))).length,
      );
      expect(unnamed).toBe(0);

      if (p.name === "home") {
        await expect(page.locator("[data-live-stats]")).toHaveAttribute("data-state", "live");
      }
      await page.evaluate(() => document.fonts.ready);

      const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
      expect(overflow, "no horizontal page scroll").toBeLessThanOrEqual(0);

      await page.screenshot({ path: join(SCREENSHOT_DIR, `${info.project.name}-${p.name}.png`), fullPage: true });
      expect(errors).toEqual([]);
    });
  }
});

test.describe("site", () => {
  test("internal links resolve", async ({ page, request }) => {
    await mockNetwork(page);
    const hrefs = new Set<string>();
    for (const p of PAGES) {
      await page.goto(p.path);
      for (const href of await page.$$eval("a[href^='/']", (as) => as.map((a) => a.getAttribute("href") ?? ""))) {
        hrefs.add(href.split("#")[0]!.split("?")[0]!);
      }
    }
    // /map/ is the separate dashboard app, added at deploy time.
    hrefs.delete("/map/");
    expect(hrefs.size).toBeGreaterThan(5);
    for (const href of hrefs) {
      const res = await request.get(href);
      expect(res.status(), href).toBe(200);
    }
  });

  test("in-page anchors exist", async ({ page }) => {
    await mockNetwork(page);
    for (const p of PAGES) {
      await page.goto(p.path);
      const missing = await page.$$eval("a[href*='#']", (as) =>
        as
          .map((a) => new URL((a as HTMLAnchorElement).href))
          .filter((u) => u.origin === location.origin && u.hash.length > 1)
          .filter((u) => u.pathname === location.pathname && !document.getElementById(decodeURIComponent(u.hash.slice(1))))
          .map((u) => u.hash),
      );
      expect(missing, p.path).toEqual([]);
    }
  });

  test("sitemap and robots.txt", async ({ request }) => {
    const sitemap = await (await request.get("/sitemap.xml")).text();
    for (const p of PAGES) expect(sitemap).toContain(`${p.path}</loc>`);
    const robots = await (await request.get("/robots.txt")).text();
    expect(robots).toMatch(/Sitemap: https?:\/\/.+\/sitemap\.xml/);
  });

  test("no /map/ or /api/ pages are generated by this site", async ({ request }) => {
    expect((await request.get("/map/")).status()).toBe(404);
    expect((await request.get("/api/v1/stats")).status()).toBe(404);
  });

  test("keyboard: skip link moves focus to the main content", async ({ page }) => {
    await mockNetwork(page);
    await page.goto("/how-it-works/");
    await page.keyboard.press("Tab");
    const skip = page.getByRole("link", { name: "Skip to content" });
    await expect(skip).toBeFocused();
    await page.keyboard.press("Enter");
    await expect(page.locator("main")).toBeFocused();
  });

  test("navigation menu works on small screens", async ({ page }, info) => {
    await mockNetwork(page);
    await page.goto("/");
    const toggle = page.getByRole("button", { name: "Menu" });
    const nav = page.getByRole("navigation", { name: "Main" });
    if (info.project.name === "desktop") {
      await expect(toggle).toBeHidden();
      await expect(nav.getByRole("link", { name: "How it works" })).toBeVisible();
      return;
    }
    await expect(toggle).toBeVisible();
    await expect(toggle).toHaveAttribute("aria-expanded", "false");
    await expect(nav.getByRole("link", { name: "How it works" })).toBeHidden();
    await toggle.click();
    await expect(toggle).toHaveAttribute("aria-expanded", "true");
    await expect(nav.getByRole("link", { name: "How it works" })).toBeVisible();
    await page.waitForTimeout(400); // let the icon's 0.2 s transition finish
    await page.screenshot({ path: join(SCREENSHOT_DIR, "mobile-menu-open.png") });
    await page.keyboard.press("Escape");
    await expect(toggle).toHaveAttribute("aria-expanded", "false");
    await expect(toggle).toBeFocused();
  });

  test("prefers-reduced-motion stops animations", async ({ page }) => {
    await page.emulateMedia({ reducedMotion: "reduce" });
    await mockNetwork(page, { stats: "ok", volunteers: "ok" });
    await page.goto("/");
    await expect(page.locator("[data-live-stats]")).toHaveAttribute("data-state", "live");
    await page.waitForTimeout(200);
    const running = await page.evaluate(() => document.getAnimations().filter((a) => a.playState === "running").length);
    expect(running).toBe(0);
  });
});
